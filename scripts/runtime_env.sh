#!/usr/bin/env bash
# Shared runtime paths. Generated data stays outside the Git repository.
PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MEM0_WORKSPACE_ROOT="${MEM0_WORKSPACE_ROOT:-$(cd "$PROJECT_ROOT/.." && pwd)}"
MEM0_RUNTIME_ROOT="${MEM0_RUNTIME_ROOT:-$MEM0_WORKSPACE_ROOT/mem0-runtime}"
MEM0_MODEL_ROOT="${MEM0_MODEL_ROOT:-$MEM0_WORKSPACE_ROOT/models}"
MEM0_CONDA_ROOT="${MEM0_CONDA_ROOT:-$MEM0_RUNTIME_ROOT/conda}"
MEM0_CACHE_ROOT="${MEM0_CACHE_ROOT:-$MEM0_RUNTIME_ROOT/cache}"
MEM0_HOME_ROOT="${MEM0_HOME_ROOT:-$MEM0_RUNTIME_ROOT/home}"
MEM0_TMP_ROOT="${MEM0_TMP_ROOT:-$MEM0_RUNTIME_ROOT/tmp}"
MEM0_DATA_ROOT="${MEM0_DATA_ROOT:-$MEM0_RUNTIME_ROOT/data}"
MEM0_RESULTS_ROOT="${MEM0_RESULTS_ROOT:-$MEM0_RUNTIME_ROOT/results}"
MEM0_LOG_ROOT="${MEM0_LOG_ROOT:-$MEM0_RUNTIME_ROOT/logs}"
MEM0_SECRETS_ROOT="${MEM0_SECRETS_ROOT:-$MEM0_RUNTIME_ROOT/secrets}"
MEM0_PYTHON="${MEM0_PYTHON:-$MEM0_CONDA_ROOT/envs/mem0/bin/python}"
VLLM_BIN="${VLLM_BIN:-$MEM0_CONDA_ROOT/envs/vllm/bin/vllm}"

export MEM0_WORKSPACE_ROOT MEM0_RUNTIME_ROOT MEM0_MODEL_ROOT MEM0_CONDA_ROOT
export MEM0_CACHE_ROOT MEM0_HOME_ROOT MEM0_TMP_ROOT MEM0_DATA_ROOT
export MEM0_RESULTS_ROOT MEM0_LOG_ROOT MEM0_SECRETS_ROOT MEM0_PYTHON VLLM_BIN
export MEM0_REPRO_ROOT="$PROJECT_ROOT"
export HOME="$MEM0_HOME_ROOT"
export XDG_CACHE_HOME="$MEM0_CACHE_ROOT"
export PIP_CACHE_DIR="$MEM0_CACHE_ROOT/pip"
export HF_HOME="$MEM0_CACHE_ROOT/huggingface"
export HUGGINGFACE_HUB_CACHE="$MEM0_CACHE_ROOT/huggingface/hub"
export TORCH_HOME="$MEM0_CACHE_ROOT/torch"
export VLLM_CACHE_ROOT="$MEM0_CACHE_ROOT/vllm"
export TRITON_CACHE_DIR="$MEM0_CACHE_ROOT/triton"
export UV_CACHE_DIR="$MEM0_CACHE_ROOT/uv"
export CONDA_PKGS_DIRS="$MEM0_CONDA_ROOT/pkgs"
export CONDA_ENVS_PATH="$MEM0_CONDA_ROOT/envs"
export TMPDIR="$MEM0_TMP_ROOT"
export MEM0_TELEMETRY=False
export TOKENIZERS_PARALLELISM=false

mkdir -p "$MEM0_HOME_ROOT" "$MEM0_CACHE_ROOT" "$MEM0_TMP_ROOT" \
  "$MEM0_DATA_ROOT" "$MEM0_RESULTS_ROOT" "$MEM0_LOG_ROOT" "$MEM0_SECRETS_ROOT"
